'use strict';

function mk(title, year, opts) {
  opts = opts || {};
  const slug = String(title).toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
  return {
    id: 'tmdb_' + slug + '_' + year,
    title,
    trTitle: opts.tr || null,
    year,
    region: opts.region === 'tr' ? 'tr' : 'hollywood',
    categories: opts.cats || ['Hollywood'],
    series: opts.series || '',
    d: opts.d || 'medium',
    pop: opts.pop || 'high',
    answers: [title, opts.tr].filter(Boolean),
  };
}

